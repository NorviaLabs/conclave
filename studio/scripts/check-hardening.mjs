import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {runInNewContext} from 'node:vm';
import {canvasMarkup,canvasContentScrolls} from '../web/canvas-ui.js';
const args={width:800,height:600,metrics:{nodeWidth:350,nodeHeight:220},edges:'<g role="button" tabindex="0"></g>',nodes:''};
const plan=canvasMarkup({...args,mode:'plan'});
assert.match(plan,/<svg[^>]*role="group" aria-label="Workflow connections"/);
assert.doesNotMatch(plan,/<svg class="canvas-edges"[^>]*aria-hidden="true"/);
assert.match(canvasMarkup({...args,mode:'run',edges:''}),/<svg class="canvas-edges"[^>]*aria-hidden="true"/);
globalThis.getComputedStyle=node=>node.style;
const area={};
const node={parentElement:area,style:{overflowY:'auto',overflowX:'hidden'},scrollHeight:300,clientHeight:100,scrollWidth:100,clientWidth:100};
assert.equal(canvasContentScrolls(node,area,0,20),true);
assert.equal(canvasContentScrolls(node,area,0,-20),true);
assert.equal(canvasContentScrolls(node,area,20,0),false);
node.scrollHeight=100;
assert.equal(canvasContentScrolls(node,area,0,20),false);
node.style={overflowY:'hidden',overflowX:'scroll'};node.scrollWidth=300;
assert.equal(canvasContentScrolls(node,area,20,0),true);
assert.equal(canvasContentScrolls({parentElement:node,style:{}},area,20,0),true);
assert.equal(canvasContentScrolls(area,area,0,20),false);
delete globalThis.getComputedStyle;
const source=await readFile(new URL('../web/studio.js',import.meta.url),'utf8');
assert.match(source,/if\(!event.ctrlKey&&!event.metaKey&&canvasContentScrolls\(event.target,area,event.deltaX,event.deltaY\)\)return;/);
const restore=source.slice(source.indexOf('  if(focusId){const replacement='),source.indexOf('\n}',source.indexOf('  if(focusId){const replacement=')));
let focused=false,range;
const replacement={focus:options=>{focused=options.preventScroll;},setSelectionRange:(...value)=>range=value};
const dialog={scrollTop:0};
runInNewContext(restore,{focusId:'dialog-goal',selection:[2,4],scrollTop:80,document:{getElementById:()=>replacement},$:()=>dialog});
assert.equal(focused,true);assert.deepEqual(range,[2,4]);assert.equal(dialog.scrollTop,80);
runInNewContext(restore,{focusId:'removed-field',selection:null,scrollTop:20,document:{getElementById:()=>null},$:()=>dialog});
assert.equal(dialog.scrollTop,20);
console.log('PASS: accessible plan connections, nested canvas scrolling, and editor focus/selection restoration.');
