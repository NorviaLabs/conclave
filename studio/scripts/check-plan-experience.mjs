// Offline Plan interactions use the production mutation helpers, not a second model.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {emptyDefinition,planConnections,canvasPositions,validateDefinition} from '../shared/definition.js';
const shared=new URL('../shared/definition.js',import.meta.url).href;
const load=async(path,replacements)=>{let source=await readFile(new URL(path,import.meta.url),'utf8');for(const [name,url]of replacements)source=source.replaceAll(`'${name}'`,JSON.stringify(url));return 'data:text/javascript,'+encodeURIComponent(source);};
const planURL=await load('../web/plan.js',[['/definition.js',shared]]);
const {insertPlanStep,placeInsertedStep,reorderPlan,duplicatePlanStep,removePlanStep,connectPlanSteps,disconnectPlanSteps,copyStepMember,moveCanvasStep,layoutSaveDefinition,planReadiness}=await import(planURL);
const {describeDefinitionChanges,proposePlanChange}=await import(await load('../web/plan-assistant.js',[['/definition.js',shared],['/plan.js',planURL],['/catalogue.js',new URL('../shared/catalogue.js',import.meta.url).href]]));
const d=emptyDefinition(),base=d.workflow[0];
d.workflow=Array.from({length:5},(_,index)=>({...base,id:`step_${index}`,name:`Work ${index}`,task:'Complete the assigned work.'}));
delete d.connections;
const edges=planConnections(d);
assert.deepEqual(planConnections(reorderPlan(d,'step_4',0)),edges,'list reordering preserves implicit dependencies');
const inserted=insertPlanStep(d,'ai',2),id=inserted.workflow[2].id;
assert.deepEqual(planConnections(inserted),edges,'inserting does not silently rewire neighbours');
let human=insertPlanStep(d,'human',d.workflow.length),review=human.workflow.at(-1).id;
human=placeInsertedStep(human,review,{after:'step_1',before:'step_2'});
assert(human.connections.some(edge=>edge.from==='step_1'&&edge.to===review));
assert(human.connections.some(edge=>edge.from===review&&edge.to==='step_2'));
assert(!human.connections.some(edge=>edge.from==='step_1'&&edge.to==='step_2'));
assert(human.connections.some(edge=>edge.from==='step_3'&&edge.to==='step_4'),'unrelated dependencies stay intact');
let parallel=placeInsertedStep(inserted,id,{parallel:'step_2'});
assert(parallel.connections.some(edge=>edge.from==='step_1'&&edge.to===id));
assert(parallel.connections.some(edge=>edge.from==='step_1'&&edge.to==='step_2'));
assert.throws(()=>connectPlanSteps(d,'step_4','step_0'),/loop/);
const disconnected=disconnectPlanSteps(d,'step_1','step_2');
assert.equal(disconnected.connections.length,edges.length-1);
assert.deepEqual(connectPlanSteps(disconnected,'step_1','step_2').connections.sort((a,b)=>a.from.localeCompare(b.from)),edges);
const duplicated=duplicatePlanStep(d,'step_2'),copy=duplicated.workflow[3];
assert.equal(copy.agent,d.workflow[2].agent,'duplicate explicitly reuses member');
assert(duplicated.connections.some(edge=>edge.from==='step_1'&&edge.to===copy.id));
const separate=copyStepMember(duplicated,copy.id);
assert.notEqual(separate.workflow[3].agent,copy.agent);
assert.equal(separate.workflow[2].agent,copy.agent,'other steps retain shared member');
separate.agents.find(member=>member.id===separate.workflow[3].agent).instructions='Independent responsibility';
assert.notEqual(separate.agents.find(member=>member.id===copy.agent).instructions,'Independent responsibility');
const removed=removePlanStep(d,'step_2');
assert.deepEqual(removed.connections,edges.filter(edge=>edge.from!=='step_2'&&edge.to!=='step_2'),'removal does not create new edges');
const moved=moveCanvasStep(d,'step_0',100,200);
assert.deepEqual(planConnections(moved),edges);
assert.deepEqual(canvasPositions(moved).step_0,{x:100,y:200});
moved.workflow[0].task='Unsaved changes';
const layout=layoutSaveDefinition(d,moved);
assert.equal(layout.workflow[0].task,d.workflow[0].task,'layout save never saves unfinished text');
assert.deepEqual(layout.canvas,moved.canvas);
const invalid=structuredClone(d);invalid.workflow[1].task='';
assert(planReadiness(invalid).some(issue=>issue.stage==='step_1'&&issue.severity==='error'));
const limited=structuredClone(d);limited.run_budget.max_delegations=0;
assert(planReadiness(limited).some(issue=>issue.severity==='error'));
const unavailable=structuredClone(d);unavailable.agents[0].tools=['read_file'];
assert(planReadiness(unavailable,{tools:[]}).some(issue=>issue.message.includes('unavailable')));
const proposal=proposePlanChange(d,'Add a human checkpoint');
assert.equal(d.workflow.length,5,'proposal does not mutate draft');
assert.equal(proposal.definition.workflow.length,6);
assert.deepEqual(planConnections(proposal.definition),edges,'standalone proposal adds no invented dependency');
const descriptions=describeDefinitionChanges(d,human);
assert(descriptions.some(change=>change.startsWith('Connect')));
assert(descriptions.some(change=>change.startsWith('Disconnect')));
const toolChanges=describeDefinitionChanges(d,unavailable);
assert(toolChanges.some(change=>change.startsWith('Tool access')));
validateDefinition(human);validateDefinition(parallel);
console.log('PASS: five-step workflow, explicit parallel/between insertion, shared-member copy, connection/cycle safety, presentation-only reorder/move, draft-safe layout save, readiness and explicit proposals.');

const canvasURL=new URL('../web/canvas-ui.js',import.meta.url).href;
const activityURL=await load('../web/run-activity.js',[['/canvas-ui.js',canvasURL]]);
const runURL=await load('../web/run-canvas.js',[['/definition.js',shared],['/canvas-ui.js',canvasURL],['/run-activity.js',activityURL]]);
const {workbenchMarkup}=await import(await load('../web/workbench-ui.js',[['/definition.js',shared],['/plan.js',planURL],['/run-canvas.js',runURL],['/catalogue.js',new URL('../shared/catalogue.js',import.meta.url).href],['/canvas-ui.js',new URL('../web/canvas-ui.js',import.meta.url).href],['/run-activity.js',activityURL]]));
const ctx={escape:value=>String(value??'').replaceAll('<','&lt;'),field:label=>`<label>${label}</label>`,agentName:(definition,id)=>definition.agents.find(member=>member.id===id)?.name||id,outputName:(definition,key)=>definition.state.find(output=>output.key===key)?.label||key,capabilityName:id=>id,selectedId:'step_1',pane:'steps',members:[],showResources:false,showInspector:false,assistantText:'',runtime:{}};
const markup=workbenchMarkup(d,ctx);
assert.match(markup,/workbench-inspector" hidden/);assert.match(markup,/workbench-resources" hidden/);
// The card names what runs the step; the tool chips stay out of the way.
assert.match(markup,/class="step-backend"/);
assert.doesNotMatch(markup,/step-tool-chips/);
assert.match(markup,/What happens\?/);assert.match(markup,/Who does it\?/);assert.match(markup,/What does it produce\?/);
assert.match(markup,/Changes to this agent affect all 5/);
assert.match(markup,/edit-shared-member/);assert.match(markup,/isolate-member/);
assert.match(markup,/data-action="suggest-plan-change"/);
assert.doesNotMatch(markup,/plan-assistant-panel/);
const ready=workbenchMarkup(invalid,{...ctx,showReadiness:true,showInspector:true});
assert.match(ready,/Blocking/);assert.match(ready,/data-plan-select="step_1"/);assert.match(ready,/node-validation/);
const proposalMarkup=workbenchMarkup(d,{...ctx,showAssistant:true,proposal});
assert.match(proposalMarkup,/data-action="apply-proposal"/);assert.match(proposalMarkup,/data-action="discard-proposal"/);assert.match(proposalMarkup,/Advanced details/);
console.log('PASS: closed-by-default panels, simple nodes, three-question editor, shared-agent scope/copy, node validation, actionable readiness and explicit proposal review.');
